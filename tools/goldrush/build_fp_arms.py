TRIS_GLOVE = int(sys.argv[sys.argv.index("--tris") + 1]) if "--tris" in sys.argv else 4200
TRIS_SLEEVE = 1500
H = 0.0013                                                      # voxel (m)

# ---------------------------------------------------------------------------------------------- the model (right hand)
WRIST_W = 0.035                                                   # the IK wrist (where the sleeve meets the glove), z
ELBOW_Z = WRIST_W + 0.28
SHOULDER_Z = ELBOW_Z + 0.31
FINGERS = [(-0.029, 0.04, 0.034, 0.0112), (-0.0098, 0.045, 0.037, 0.0118), (0.0098, 0.042, 0.034, 0.0112), (0.028, 0.033, 0.027, 0.0098)]
KNUCKLE_Z = -0.088
THUMB_ORIGIN = np.array([-0.04, -0.006, -0.026])
THUMB_EULER = (-0.2, 0.85, -0.5)                                  # XYZ, as three.js


def euler_xyz(a, b, c):
    ca, sa, cb, sb, cc, sc = math.cos(a), math.sin(a), math.cos(b), math.sin(b), math.cos(c), math.sin(c)
    Rx = np.array([[1, 0, 0], [0, ca, -sa], [0, sa, ca]])
    Ry = np.array([[cb, 0, sb], [0, 1, 0], [-sb, 0, cb]])
    Rz = np.array([[cc, -sc, 0], [sc, cc, 0], [0, 0, 1]])
    return Rx @ Ry @ Rz


def quat_from_matrix(R):
    t = np.trace(R)
    if t > 0:
        s = math.sqrt(t + 1) * 2
        return np.array([(R[2, 1] - R[1, 2]) / s, (R[0, 2] - R[2, 0]) / s, (R[1, 0] - R[0, 1]) / s, 0.25 * s])
    i = int(np.argmax(np.diag(R)))
    j, k = (i + 1) % 3, (i + 2) % 3
    s = math.sqrt(R[i, i] - R[j, j] - R[k, k] + 1) * 2
    q = np.zeros(4)
    q[i] = 0.25 * s
    q[j] = (R[j, i] + R[i, j]) / s
    q[k] = (R[k, i] + R[i, k]) / s
    q[3] = (R[k, j] - R[j, k]) / s
    return q


def bones_right():
    """name -> dict(parent, world position, world rotation matrix, local translation, local rotation quaternion)"""
    B = {}

    def add(name, parent, pos, R=None):
        R = np.eye(3) if R is None else R
        pp = B[parent]["pos"] if parent else np.zeros(3)
        pr = B[parent]["R"] if parent else np.eye(3)
        local_t = pr.T @ (np.asarray(pos, float) - pp)
        local_R = pr.T @ R
        B[name] = {"parent": parent, "pos": np.asarray(pos, float), "R": R, "t": local_t, "q": quat_from_matrix(local_R)}

    add("upper", None, [0, -0.004, SHOULDER_Z])
    add("fore", "upper", [0, -0.004, ELBOW_Z])
    add("hand", "fore", [0, 0, 0])
    for i, (x, l1, l2, rad) in enumerate(FINGERS):
        s1, s2, s3 = l1, l2 * 0.55, l2 * 0.45
        add(f"f{i}_1", "hand", [x, 0.001, KNUCKLE_Z])
        add(f"f{i}_2", f"f{i}_1", [x, 0.001, KNUCKLE_Z - s1])
        add(f"f{i}_3", f"f{i}_2", [x, 0.001, KNUCKLE_Z - s1 - s2])
        B[f"f{i}_tip"] = {"pos": np.array([x, 0.001, KNUCKLE_Z - s1 - s2 - s3]), "R": np.eye(3)}
    Rt = euler_xyz(*THUMB_EULER)
    add("th_1", "hand", THUMB_ORIGIN, Rt)
    d = Rt @ np.array([0, 0, -1.0])
    l1, l2, l3 = 0.038, 0.034, 0.022
    add("th_2", "th_1", THUMB_ORIGIN + d * l1, Rt)
    add("th_3", "th_2", THUMB_ORIGIN + d * (l1 + l2), Rt)
    B["th_tip"] = {"pos": THUMB_ORIGIN + d * (l1 + l2 + l3), "R": Rt}
    return B


# ---------------------------------------------------------------------------------------------- signed distances
def smin(a, b, k):
    h = np.clip(0.5 + 0.5 * (b - a) / k, 0, 1)
    return b * (1 - h) + a * h - k * h * (1 - h)


def capsule(P, p0, p1, r0, r1):
    p0, p1 = np.asarray(p0, np.float32), np.asarray(p1, np.float32)
    d = p1 - p0
    L2 = float(d @ d)
    X, Y, Z = P
    t = np.clip(((X - p0[0]) * d[0] + (Y - p0[1]) * d[1] + (Z - p0[2]) * d[2]) / L2, 0, 1)
    r = r0 + (r1 - r0) * t
    return np.sqrt((X - p0[0] - t * d[0]) ** 2 + (Y - p0[1] - t * d[1]) ** 2 + (Z - p0[2] - t * d[2]) ** 2) - r


def ellipsoid(P, c, rad):
    X, Y, Z = P
    q = np.sqrt(((X - c[0]) / rad[0]) ** 2 + ((Y - c[1]) / rad[1]) ** 2 + ((Z - c[2]) / rad[2]) ** 2)
    return (q - 1.0) * min(rad)


def build_field(B, part):
    """part 'sleeve': the canvas sleeve (coarse voxels); part 'glove': the leather glove with its gauntlet cuff (fine voxels)"""
    if part == "sleeve":
        h = 0.003
        xs = np.arange(-0.06, 0.06, h, dtype=np.float32)
        ys = np.arange(-0.06, 0.06, h, dtype=np.float32)
        zs = np.arange(0.02, SHOULDER_Z + 0.03, h, dtype=np.float32)
        P = np.meshgrid(xs, ys, zs, indexing="ij")
        X, Y, Z = P
        # forearm (a little wider at the elbow), the elbow, the upper arm
        d = capsule(P, [0, -0.004, WRIST_W], [0, -0.004, ELBOW_Z], 0.033, 0.040)
        d = smin(d, capsule(P, [0, -0.004, ELBOW_Z], [0, -0.004, SHOULDER_Z + 0.02], 0.042, 0.047), 0.012)
        # cloth folds near the elbow and the wrist
        fold = 0.0011 * np.sin(Z * 210.0 + np.sin(X * 90.0) * 2.0) * np.exp(-(((Z - ELBOW_Z) / 0.05) ** 2)) + 0.0007 * np.sin(Z * 260.0 + X * 40.0) * np.exp(-(((Z - 0.07) / 0.03) ** 2))
        return d + fold.astype(np.float32), (xs, ys, zs), h
    xs = np.arange(-0.078, 0.078, H, dtype=np.float32)
    ys = np.arange(-0.062, 0.078, H, dtype=np.float32)
    zs = np.arange(-0.215, 0.075, H, dtype=np.float32)
    P = np.meshgrid(xs, ys, zs, indexing="ij")
    X, Y, Z = P
    # the gauntlet cuff (flared, over the sleeve) with its rolled rim
    d = capsule(P, [0, -0.002, -0.004], [0, -0.002, 0.046], 0.0375, 0.0405)
    ring = np.sqrt((np.sqrt(X ** 2 + (Y + 0.002) ** 2) - 0.0392) ** 2 + (Z + 0.003) ** 2) - 0.0048
    d = smin(d, ring, 0.003)
    # the glove: palm, padded back, knuckle bar
    d = smin(d, ellipsoid(P, [0, 0, -0.047], [0.047, 0.021, 0.052]), 0.006)
    d = smin(d, ellipsoid(P, [0, 0.012, -0.05], [0.04, 0.012, 0.042]), 0.006)
    d = smin(d, capsule(P, [-0.032, 0.002, -0.086], [0.032, 0.002, -0.086], 0.0135, 0.0125), 0.004)
    # fingers: three joints each; a bulge at each joint (the glove's creases are in the vertex colours)
    for i, (x, l1, l2, rad) in enumerate(FINGERS):
        rad = rad * 0.8                                           # (the old capsules overlapped: slimmer, so the fingers read as fingers)
        a, b, c, e = B[f"f{i}_1"]["pos"], B[f"f{i}_2"]["pos"], B[f"f{i}_3"]["pos"], B[f"f{i}_tip"]["pos"]
        d = smin(d, capsule(P, a, b, rad, rad * 0.97), 0.003)
        d = smin(d, capsule(P, b, c, rad * 0.97, rad * 0.93), 0.003)
        d = smin(d, capsule(P, c, e, rad * 0.93, rad * 0.8), 0.003)
        d = smin(d, ellipsoid(P, e + np.array([0, 0, 0.004]), [rad * 0.8, rad * 0.78, rad * 0.9]), 0.003)
    # thumb
    t1, t2, t3, te = B["th_1"]["pos"], B["th_2"]["pos"], B["th_3"]["pos"], B["th_tip"]["pos"]
    d = smin(d, capsule(P, t1 + (t1 - t2) * 0.15, t2, 0.0148, 0.0138), 0.004)
    d = smin(d, capsule(P, t2, t3, 0.0138, 0.0128), 0.003)
    d = smin(d, capsule(P, t3, te, 0.0128, 0.011), 0.003)
    return d, (xs, ys, zs), H


# ---------------------------------------------------------------------------------------------- mesh + skin
def seg_dist(V, a, b):
    ab = b - a
    t = np.clip(((V - a) @ ab) / float(ab @ ab), 0, 1)
    return np.linalg.norm(V - (a + t[:, None] * ab), axis=1)


def skin(V, B):
    names, segs, sig = [], [], []

    def add(n, a, b, s):
        names.append(n); segs.append((np.asarray(a), np.asarray(b))); sig.append(s)

    add("upper", B["upper"]["pos"], B["fore"]["pos"], 0.045)
    add("fore", B["fore"]["pos"], [0, -0.004, WRIST_W], 0.04)
    add("hand", [0, 0, 0.0], [0, 0, KNUCKLE_Z + 0.002], 0.032)
    for i in range(4):
        add(f"f{i}_1", B[f"f{i}_1"]["pos"], B[f"f{i}_2"]["pos"], 0.0075)
        add(f"f{i}_2", B[f"f{i}_2"]["pos"], B[f"f{i}_3"]["pos"], 0.0075)
        add(f"f{i}_3", B[f"f{i}_3"]["pos"], B[f"f{i}_tip"]["pos"], 0.0075)
    add("th_1", B["th_1"]["pos"], B["th_2"]["pos"], 0.0085)
    add("th_2", B["th_2"]["pos"], B["th_3"]["pos"], 0.0085)
    add("th_3", B["th_3"]["pos"], B["th_tip"]["pos"], 0.0085)
    W = np.zeros((len(V), len(names)), np.float32)
    for j, ((a, b), s) in enumerate(zip(segs, sig)):
        W[:, j] = np.exp(-((seg_dist(V, a, b) / s) ** 2))
    W[:, 0] += 1e-6
    # keep the four strongest, normalise
    idx = np.argsort(-W, axis=1)[:, :4]
    w4 = np.take_along_axis(W, idx, 1)
    w4 /= np.maximum(w4.sum(1, keepdims=True), 1e-9)
    return names, idx.astype(np.uint16), w4.astype(np.float32)


def colours(V, B, AO=None):
    """linear vertex colours: leather glove (palm darker, back pad lighter, creases at the finger joints), the canvas cuff and sleeve"""
    lin = lambda h: np.array([((c / 255 + 0.055) / 1.055) ** 2.4 if c / 255 > 0.04045 else c / 255 / 12.92 for c in ((h >> 16) & 255, (h >> 8) & 255, h & 255)])
    leather, cuffc, fore, upper = lin(0x9A7752), lin(0x6A5642), lin(0x6A5642), lin(0x5E4C3B)
    C = np.tile(leather, (len(V), 1)).astype(np.float64)
    x, y, z = V[:, 0], V[:, 1], V[:, 2]
    # a mottled, worn surface: slow patches + fine grain (the shader adds the relief)
    mott = 1.0 + 0.07 * np.sin(x * 190 + z * 130 + np.sin(y * 150) * 2) + 0.05 * np.sin(z * 410 - x * 270 + 1.3) + 0.03 * np.sin(y * 520 + z * 330)
    C *= mott[:, None]
    C *= np.where(y < -0.008, 0.82, 1.0)[:, None] * np.where((y > 0.012) & (z > -0.1) & (z < 0), 1.07, 1.0)[:, None]
    # creases: a dark ring at every finger joint, a seam down the middle of the back of the hand and along each finger's side
    for i in range(4):
        fx = FINGERS[i][0]
        for nm in (f"f{i}_2", f"f{i}_3"):
            zj = B[nm]["pos"][2]
            near = (np.abs(z - zj) < 0.0022) & (np.abs(x - fx) < 0.014)
            C[near] *= 0.78
        C[(np.abs(x - fx) < 0.0011) & (np.abs(y - 0.001) > 0.007) & (z < KNUCKLE_Z) & (z > -0.2)] *= 0.72
    C[(np.abs(x) < 0.0011) & (y > 0.015) & (z > -0.1) & (z < -0.002)] *= 0.7
    C[(z > -0.02) & (z < 0.002) & (y > 0.02)] *= 0.9
    # the cuff / sleeve by z
    t = np.clip((z - 0.0) / 0.012, 0, 1)[:, None]
    C = C * (1 - t) + cuffc * t
    t = np.clip((z - 0.05) / 0.02, 0, 1)[:, None]
    C = C * (1 - t) + fore * t
    t = np.clip((z - ELBOW_Z) / 0.06, 0, 1)[:, None]
    C = C * (1 - t) + upper * t
    C[(np.abs(z + 0.005) < 0.004) & (np.sqrt(x ** 2 + (y + 0.002) ** 2) > 0.037)] *= 0.62        # the dark rolled rim of the cuff
    if AO is not None:                                                                            # baked contact shading: creases between fingers, under the cuff
        C *= (0.55 + 0.45 * AO)[:, None]
    return C.astype(np.float32)


def build_mesh(B, part, target):
    d, (xs, ys, zs), h = build_field(B, part)
    verts, faces, normals, _ = measure.marching_cubes(d, 0.0, spacing=(h, h, h), gradient_direction="ascent")
    verts = verts + np.array([xs[0], ys[0], zs[0]])
    print(part, "marching cubes:", len(verts), "verts", len(faces), "faces", flush=True)
    m = trimesh.Trimesh(verts, faces, process=True)
    v2, f2 = fast_simplification.simplify(np.asarray(m.vertices, np.float32), np.asarray(m.faces, np.int32), target_count=target, agg=3)
    m2 = trimesh.Trimesh(v2, f2, process=False)
    m2.merge_vertices()
    m2.update_faces(m2.nondegenerate_faces())
    m2.remove_unreferenced_vertices()
    # drop dust only: every piece of a few dozen faces stays (the decimation may cut thin joints into separate pieces)
    parts = [pt for pt in m2.split(only_watertight=False) if len(pt.faces) >= 40]
    print("pieces:", [len(pt.faces) for pt in parts], flush=True)
    m2 = trimesh.util.concatenate(parts)
    vol = float(m2.volume)
    if vol < 0:                                                   # (inside out: marching cubes' winding depends on the field's sign)
        m2.invert()
    print("decimated:", len(m2.vertices), "verts", len(m2.faces), "faces, volume", round(vol * 1e6, 1), "cm3 (flipped)" if vol < 0 else "cm3", flush=True)
    m2 = trimesh.Trimesh(np.asarray(m2.vertices), np.asarray(m2.faces), process=False)          # (fresh normals from the final winding)
    Vn, Nn = np.asarray(m2.vertices, np.float32), np.asarray(m2.vertex_normals, np.float32)
    radial = Vn[:, :2] - np.array([0.0, -0.004], np.float32)
    out = float(np.mean(np.sum(Nn[:, :2] * radial, axis=1) > 0))
    print(part, "share of normals pointing outward:", round(out, 3), flush=True)
    # ambient occlusion baked from the signed field: how much open space lies 7 mm out along the normal (1 = open)
    from scipy.ndimage import map_coordinates
    probe = Vn + Nn * 0.007
    idx = [(probe[:, k] - o[0]) / h for k, o in enumerate((xs, ys, zs))]
    sd = map_coordinates(d, idx, order=1, mode="nearest")
    ao = np.clip(sd / 0.007, 0.0, 1.0).astype(np.float32)
    return Vn, np.asarray(m2.faces, np.uint32), Nn, ao


# ---------------------------------------------------------------------------------------------- glTF writer
class Glb:
    def __init__(self):
        self.bin = bytearray()
        self.views, self.accs = [], []

    def add(self, arr, ctype, atype, target=None, minmax=False):
        data = np.ascontiguousarray(arr).tobytes()
        while len(self.bin) % 4:
            self.bin.append(0)
        view = {"buffer": 0, "byteOffset": len(self.bin), "byteLength": len(data)}
        if target:
            view["target"] = target
        self.bin += data
        self.views.append(view)
        acc = {"bufferView": len(self.views) - 1, "componentType": ctype, "count": int(arr.shape[0]), "type": atype}
        if minmax:
            mn, mx = np.atleast_1d(arr.min(0)), np.atleast_1d(arr.max(0))
            acc["min"] = [float(x) for x in mn]
            acc["max"] = [float(x) for x in mx]
        self.accs.append(acc)
        return len(self.accs) - 1


FLOAT, USHORT, UINT = 5126, 5123, 5125


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    B = bones_right()
    # two meshes: the glove (fine - the fingers must read) and the sleeve (coarse); the sleeve runs on inside the gauntlet cuff
    Vg, Fg, Ng, Ag = build_mesh(B, "glove", TRIS_GLOVE)
    Vsl, Fsl, Nsl, Asl = build_mesh(B, "sleeve", TRIS_SLEEVE)
    V = np.concatenate([Vg, Vsl])
    N = np.concatenate([Ng, Nsl])
    AO = np.concatenate([Ag, Asl])
    F = np.concatenate([Fg, Fsl + len(Vg)]).astype(np.uint32)
    n_glove = len(Fg)
    names, J, Wt = skin(V, B)
    C = colours(V, B, AO)
    g = Glb()
    nodes, meshes, skins, scene_nodes, anims = [], [], [], [], []
    for side, tag in ((1, "R"), (-1, "L")):
        mir = np.array([side, 1, 1], np.float32)
        Vs, Ns = V * mir, N * mir
        Fs = F if side == 1 else F[:, ::-1].copy()
        # bones (a mirror flips x of every position; the bone axes stay the glove frame's, the thumb's rest rotation mirrors)
        order = ["upper", "fore", "hand"] + [f"f{i}_{j}" for i in range(4) for j in (1, 2, 3)] + ["th_1", "th_2", "th_3"]
        base = len(nodes)
        index = {n: base + 1 + k for k, n in enumerate(order)}
        nodes.append({"name": f"armature_{tag}", "children": [index["upper"]]})
        children = {n: [] for n in order}
        for n in order:
            p = B[n]["parent"]
            if p:
                children[p].append(index[n])
        for n in order:
            b = B[n]
            t = b["t"] * mir
            q = b["q"].copy()
            if side == -1:                                                    # mirror of a rotation about the x axis plane: (x, y, z, w) -> (x, -y, -z, w)
                q = np.array([q[0], -q[1], -q[2], q[3]])
            node = {"name": f"{tag}_{n}", "translation": [float(v) for v in t], "rotation": [float(v) for v in q]}
            if children[n]:
                node["children"] = children[n]
            nodes.append(node)
        # inverse bind matrices from the rest world transforms
        ibm = []
        for n in order:
            Rw = B[n]["R"].copy()
            pos = B[n]["pos"] * mir
            if side == -1:
                Rw = np.diag([-1, 1, 1]) @ Rw @ np.diag([-1, 1, 1])
            Mw = np.eye(4)
            Mw[:3, :3] = Rw
            Mw[:3, 3] = pos
            ibm.append(np.linalg.inv(Mw).T.astype(np.float32))                # (column-major: transpose of row-major)
        ibm = np.array(ibm, np.float32).reshape(-1, 16)
        ibm_acc = g.add(ibm.reshape(len(order), 16), FLOAT, "MAT4")
        # joints: the order of `names` (the skin weights) -> node indices
        map_j = {n: k for k, n in enumerate(order)}
        remap = np.array([map_j[n] if n in map_j else 0 for n in names], np.uint16)
        Jn = remap[J]
        skin_i = len(skins)
        skins.append({"name": f"skin_{tag}", "joints": [index[n] for n in order], "inverseBindMatrices": ibm_acc, "skeleton": base})
        # the two primitives: glove (z < 0.045) and sleeve
        cz = np.where(np.arange(len(Fs)) < n_glove, 0.0, 1.0)                   # (the first n_glove faces are the glove's)
        prims = []
        pos_acc = g.add(Vs.astype(np.float32), FLOAT, "VEC3", 34962, True)
        nor_acc = g.add(Ns.astype(np.float32), FLOAT, "VEC3", 34962)
        col_acc = g.add(C.astype(np.float32), FLOAT, "VEC3", 34962)
        jnt_acc = g.add(Jn.astype(np.uint16), USHORT, "VEC4", 34962)
        wgt_acc = g.add(Wt.astype(np.float32), FLOAT, "VEC4", 34962)
        for mname, sel in (("glove", cz < 0.5), ("sleeve", cz >= 0.5)):
            idx = Fs[sel].astype(np.uint32).reshape(-1)
            ia = g.add(idx, UINT, "SCALAR", 34963)
            prims.append({"attributes": {"POSITION": pos_acc, "NORMAL": nor_acc, "COLOR_0": col_acc, "JOINTS_0": jnt_acc, "WEIGHTS_0": wgt_acc}, "indices": ia, "material": 0 if mname == "glove" else 1, "extras": {"part": mname}})
        meshes.append({"name": f"arm_{tag}", "primitives": prims})
        mesh_node = len(nodes)
        nodes.append({"name": f"arm_{tag}", "mesh": len(meshes) - 1, "skin": skin_i})
        scene_nodes += [base, mesh_node]
        # clips: curl (the fingers closing; the game's old two-joint curl split over three joints) and thumb
        t_acc = g.add(np.array([0, 0.25, 0.5, 0.75, 1.0], np.float32), FLOAT, "SCALAR", None, True)
        samplers, channels = [], []

        def track(node_name, angles):
            q = np.array([[math.sin(a / 2), 0, 0, math.cos(a / 2)] for a in angles], np.float32)
            samplers.append({"input": t_acc, "output": g.add(q, FLOAT, "VEC4"), "interpolation": "LINEAR"})
            channels.append({"sampler": len(samplers) - 1, "target": {"node": index[node_name], "path": "rotation"}})

        ks = [0, 0.25, 0.5, 0.75, 1.0]
        for i in range(4):
            f = 1 - i * 0.04
            track(f"f{i}_1", [-0.12 - k * 1.05 * f for k in ks])
            track(f"f{i}_2", [(-0.08 - k * 1.25 * f) * 0.58 for k in ks])
            track(f"f{i}_3", [(-0.08 - k * 1.25 * f) * 0.42 - 0.04 * k for k in ks])
        anims.append({"name": f"curl_{tag}", "samplers": samplers, "channels": channels})
        samplers, channels = [], []
        for nm, share in (("th_2", 0.6), ("th_3", 0.4)):
            track(nm, [(-0.15 - k * 0.9) * share for k in ks])
        anims.append({"name": f"thumb_{tag}", "samplers": samplers, "channels": channels})
    gltf = {
        "asset": {"version": "2.0", "generator": "goldrush build_fp_arms.py"},
        "scene": 0, "scenes": [{"nodes": scene_nodes}], "nodes": nodes, "meshes": meshes, "skins": skins, "animations": anims,
        "materials": [{"name": "glove_leather", "pbrMetallicRoughness": {"baseColorFactor": [1, 1, 1, 1], "metallicFactor": 0, "roughnessFactor": 0.86}},
                      {"name": "sleeve_canvas", "pbrMetallicRoughness": {"baseColorFactor": [1, 1, 1, 1], "metallicFactor": 0, "roughnessFactor": 0.95}}],
        "buffers": [{"byteLength": len(g.bin)}], "bufferViews": g.views, "accessors": g.accs,
    }
    js = json.dumps(gltf, separators=(",", ":")).encode()
    js += b" " * ((4 - len(js) % 4) % 4)
    binb = bytes(g.bin) + b"\0" * ((4 - len(g.bin) % 4) % 4)
    out = struct.pack("<4sII", b"glTF", 2, 12 + 8 + len(js) + 8 + len(binb)) + struct.pack("<I4s", len(js), b"JSON") + js + struct.pack("<I4s", len(binb), b"BIN\0") + binb
    (OUT / "fp_arms.glb").write_bytes(out)
    (OUT / "manifest.json").write_text(json.dumps({
        "about": "First-person arms for GoldRush (FP2.0A): two skinned work-glove arms (right / mirrored left) with finger skeleton and curl / thumb clips",
        "origin": "own work - generated by tools/goldrush/build_fp_arms.py (signed-distance model, meshed and skinned); no third-party art",
        "licence": "own - released as CC0 1.0 with the repository's assets",
        "triangles_per_arm": int(len(F)), "bones_per_arm": 3 + 12 + 3, "clips": [a["name"] for a in anims]}, indent=1))
    print("wrote", OUT / "fp_arms.glb", len(out), "bytes;", len(F), "triangles per arm")


