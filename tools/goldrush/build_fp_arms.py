"""Build GoldRush's first-person arms (FP2.0A): two skinned work-glove arms with a finger skeleton and AnimationClips.

Own work (generated by this script - no third-party art): a signed-distance model of a leather work glove with a gauntlet cuff,
knuckle pad, three-joint fingers and thumb, and a canvas sleeve up to the shoulder, meshed (marching cubes), decimated, skinned
to a bone chain and written as ONE small GLB (about 0.3 MB, no textures - the game shades it: goldrush-fprig.js):

  static/games/goldrush/assets/fp/fp_arms.glb      skinned meshes arm_R / arm_L (the left a true mirror), bones, clips
  static/games/goldrush/assets/fp/manifest.json    what is in it, origin and licence

Frame (the game's glove frame, goldrush-hand.js): the wrist at the origin, fingers towards -z, the back of the hand +y, the thumb
on -x (right hand). Rest pose: the arm straight back along +z (the forearm from the wrist at z = 0.035 to the elbow at 0.315, the
upper arm on to the shoulder at 0.625), the fingers nearly straight. Bone axes are the glove frame's at rest (the thumb's root bone
carries its rest rotation), so a curl is a rotation about the bone's own x axis.

Bones (per side, prefix R_ / L_): upper (shoulder) -> fore (elbow) -> hand (wrist) -> f0..f3 _1 _2 _3 (index .. little finger), th_1 _2 _3.
Clips (1 s, sampled by time = the 0..1 parameter): curl_R / curl_L (the four fingers closing, three joints each),
thumb_R / thumb_L (the thumb's two outer joints).

    pip install numpy scikit-image trimesh fast-simplification
    python tools/goldrush/build_fp_arms.py
"""

